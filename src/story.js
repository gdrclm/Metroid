const known = new Set(ACT_ONE_ENTRIES.map((e) => e.id));
export const newStoryState = () => ({
  entries: [],
  read: [],
  placesRead: [],
  helpRead: [],
  ending: null,
});
const strings = (raw, allowed) =>
  Array.isArray(raw)
    ? [
        ...new Set(
          raw.filter(
            (id) => typeof id === "string" && (!allowed || allowed.has(id)),
          ),
        ),
      ].slice(0, 100)
    : [];
export function normalizeStoryState(raw) {
  const state = newStoryState();
  if (!raw || typeof raw !== "object") return state;
  const seen = new Set();
  if (Array.isArray(raw.entries))
    for (const e of raw.entries) {
      if (known.has(e?.id) && !seen.has(e.id)) {
        seen.add(e.id);
        state.entries.push({
          id: e.id,
          at: Number.isFinite(e.at) ? Math.max(0, e.at) : 0,
        });
      }
    }
  state.read = strings(raw.read, seen);
  state.placesRead = strings(
    raw.placesRead,
    new Set(Object.keys(PLACE_VOICES)),
  );
  state.helpRead = strings(raw.helpRead, new Set(GUIDE_HELP.map((e) => e.id)));
  const end = raw.ending;
  if (
    end &&
    ["time", "deaths", "commands"].every(
      (k) => Number.isFinite(end[k]) && end[k] >= 0,
    )
  )
    state.ending = {
      time: end.time,
      deaths: Math.floor(end.deaths),
      commands: Math.floor(end.commands),
    };
  return state;
}
export class ActOneStory {
  constructor(director) {
    this.director = director;
  }
  get state() {
    return (this.director.state.story ||= newStoryState());
  }
  sync(notify = false) {
    const d = this.director,
      g = d.game;
    if (!d.enabled || g.prediction) return false;
    let changed = false;
    for (const entry of ACT_ONE_ENTRIES) {
      if (this.state.entries.some((e) => e.id === entry.id) || !entry.when(g))
        continue;
      this.state.entries.push({ id: entry.id, at: g.progress.playTime });
      changed = true;
      if (entry.id === "dawn" && !this.state.ending)
        this.state.ending = {
          time: g.progress.playTime,
          deaths: g.progress.deaths,
          commands: d.state.completedCommands,
        };
      if (notify) g.emit("story", entry);
    }
    return changed;
  }
  get entries() {
    return this.state.entries.map((record) => ({
      ...ACT_ONE_ENTRIES.find((e) => e.id === record.id),
      at: record.at,
    }));
  }
  get unread() {
    return this.state.entries.filter((e) => !this.state.read.includes(e.id))
      .length;
  }
  markRead(section, id) {
    const g = this.director.game;
    if (g.prediction) return;
    const field = { path: "read", places: "placesRead", help: "helpRead" }[
      section
    ];
    if (!field) return;
    const allowed =
      section === "path"
        ? this.state.entries.some((e) => e.id === id)
        : section === "places"
          ? g.progress.visited.includes(id) && Object.hasOwn(PLACE_VOICES, id)
          : GUIDE_HELP.some((e) => e.id === id);
    if (allowed && !this.state[field].includes(id)) {
      this.state[field].push(id);
      g.save();
    }
  }
  dialogue(target, text) {
    const g = this.director.game;
    if (target.id === "npc.station_keeper")
      return (
        text +
        "\n\nОна замечает, как ты прислушиваешься: «Если рядом кто-то есть, не прячь от него усталость. Голос не узнает, что тебе нужен сон, пока ты не остановишься у огня»."
      );
    if (target.id === "npc.clockmaker")
      return (
        text +
        (g.flags.includes("story.clockmaker_memory")
          ? "\n\n«Нить нужна не для того, чтобы держать тебя. По ней можно найти друг друга, когда вокруг снова станет темно»."
          : "\n\n«Ты словно ждёшь чужого разрешения на каждый шаг. Что ж, иногда дорога начинается с того, что кто-то решает идти с тобой».")
      );
    return text;
  }
}
